use ts_rs::TS;
pub fn source() -> String {
    let cfg = ts_rs::Config::default();
    let declarations = [
        crate::application::transfer::TransferProgress::decl(&cfg),
        crate::commands::ExportRequest::decl(&cfg),
        crate::domain::AppError::decl(&cfg),
        crate::domain::account::OtpKind::decl(&cfg),
        crate::domain::account::OtpAlgorithm::decl(&cfg),
        crate::domain::account::AccountInput::decl(&cfg),
        crate::domain::account::AccountSummary::decl(&cfg),
        crate::application::session::Phase::decl(&cfg),
        crate::application::core::VaultStatus::decl(&cfg),
        crate::application::core::Code::decl(&cfg),
        crate::compatibility::backup::KeyRequest::decl(&cfg),
        crate::application::transfer::ImportRow::decl(&cfg),
        crate::application::transfer::ImportPreview::decl(&cfg),
    ];
    format!(
        "// Generated by npm run bindings. Do not edit.\n{}\n",
        declarations
            .iter()
            .map(|d| format!("export {d}"))
            .collect::<Vec<_>>()
            .join("\n")
    )
}
#[cfg(test)]
mod tests {
    #[test]
    fn ipc_contracts_are_current() {
        let file =
            std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../src/lib/ipc/generated.ts");
        assert_eq!(
            std::fs::read_to_string(file).unwrap(),
            super::source(),
            "Run npm run bindings"
        );
    }
}
